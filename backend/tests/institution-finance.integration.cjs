const test = require('node:test');
const assert = require('node:assert/strict');
test('PostgreSQL tuition: school/course prices, discounts, isolation and snapshots', { skip: !process.env.TUITION_TEST_DATABASE_URL }, async () => {
  const url = new URL(process.env.TUITION_TEST_DATABASE_URL);
  assert.equal(url.hostname, '127.0.0.1'); assert.equal(url.port, '55440'); assert.equal(url.pathname, '/facilita_tuition_validation');
  process.env.DATABASE_URL = url.href;
  const { tuitionDb: db, institutionFinanceRouter: router } = require('../dist/institution-finance/router');
  const suffix = require('node:crypto').randomUUID();
  let currentId;
  const request = (path, method = 'GET', body = {}) => new Promise((resolve, reject) => {
    const layer = router.stack.find(item => item.route && item.route.methods[method.toLowerCase()] && item.match(path));
    assert.ok(layer, path);
    const req = { user: { id: currentId, role: 'coord', tenantId: 'forged' }, params: layer.params, query: {}, body };
    const res = { code: 200, status(code) { this.code = code; return this; }, json(body) { resolve({ code: this.code, body }); } };
    layer.route.stack[0].handle(req, res, reject);
  });
  const tenant = name => db.tenant.create({ data: { id: `${suffix}-${name}`, nome: name, full: '', cidade: '', color: '', cover: '', dominio: `${suffix}-${name}.invalid`, admin: '', since: '' } });
  const user = (tenantId, role, name, courseId = null) => db.user.create({ data: { tenantId, role, nome: name, email: `${suffix}-${name}@test.invalid`, password: 'not-a-login-hash', papel: '', courseId } });
  try {
    const a = await tenant('A'), b = await tenant('B');
    const med = await db.course.create({ data: { id: `${suffix}-med`, tenantId: a.id, nome: 'Medicine local test', status: 'Ativo' } });
    const law = await db.course.create({ data: { id: `${suffix}-law`, tenantId: a.id, nome: 'Law local test', status: 'Ativo' } });
    const coord = await user(a.id, 'coord', 'coordinator');
    const studentMed = await user(a.id, 'aluno', 'medicine', med.id), studentLaw = await user(a.id, 'aluno', 'law', law.id);
    const noCourse = await user(a.id, 'aluno', 'school'), foreign = await user(b.id, 'aluno', 'foreign');
    currentId = coord.id;
    const terms = { mode: 'COURSE', schoolCents: 0, dueDay: 12, startMonth: '2026-10', issuerName: 'Local test institution', issuerDocument: 'TEST ONLY', issuerAddress: 'Local test', paymentInstructions: 'Not payable', coursePrices: [{ courseId: med.id, priceCents: 100000 }, { courseId: law.id, priceCents: 50000 }], expectedVersion: null };
    const configured = await request('/settings', 'PUT', terms); assert.equal(configured.code, 200, JSON.stringify(configured.body));
    const issue = (studentId, competence, expectedSettingsVersion) => request('/invoices', 'POST', { studentId, competence, expectedSettingsVersion, totalCents: 1 });
    assert.equal((await issue(foreign.id, '2026-10', 0)).code, 404);
    assert.equal((await issue(noCourse.id, '2026-10', 0)).code, 409);
    assert.equal((await issue(studentMed.id, '2026-09', 0)).code, 400);
    const pair = await Promise.all([issue(studentMed.id, '2026-10', 0), issue(studentMed.id, '2026-10', 0)]);
    assert.deepEqual(pair.map(r => r.code).sort(), [201, 409]);
    const invoice = pair.find(r => r.code === 201).body.invoice; assert.equal(invoice.totalCents, 100000);
    const lawInvoice = await issue(studentLaw.id, '2026-10', 0); assert.equal(lawInvoice.body.invoice.totalCents, 50000);
    assert.equal((await request(`/students/${studentMed.id}`, 'PUT', { discountCents: 10000, startMonth: '2026-10', expectedSettingsVersion: 0 })).code, 200);
    assert.equal((await issue(studentMed.id, '2026-11', 0)).code, 409);
    assert.equal((await issue(studentMed.id, '2026-11', 1)).body.invoice.totalCents, 90000);
    assert.equal((await request('/settings', 'PUT', { ...terms, mode: 'SCHOOL', schoolCents: 30000, expectedVersion: 1 })).code, 200);
    const school = await issue(noCourse.id, '2026-11', 2); assert.equal(school.code, 201, JSON.stringify(school.body)); assert.equal(school.body.invoice.totalCents, 30000);
    assert.equal((await request(`/students/${noCourse.id}`, 'PUT', { scholarship: true, discountCents: 0, startMonth: '2026-10', expectedSettingsVersion: 2 })).code, 200);
    const exempt = await issue(noCourse.id, '2026-12', 3); assert.equal(exempt.body.invoice.status, 'EXEMPT'); assert.equal(exempt.body.invoice.totalCents, 0);
    assert.equal((await request(`/invoices/${exempt.body.invoice.id}/status`, 'PATCH', { status: 'PAID', expectedVersion: 0, note: 'Must not mark exemption paid' })).code, 409);
    assert.equal((await db.tuitionInvoice.findUniqueOrThrow({ where: { id: invoice.id } })).totalCents, 100000);
    assert.equal((await request(`/invoices/${invoice.id}/status`, 'PATCH', { status: 'PAID', expectedVersion: 0, note: 'Internal reference only' })).code, 200);
    currentId = studentMed.id;
    const mine = await request('/my-invoices'); assert.equal(mine.code, 200); assert.equal(mine.body.invoices.length, 2);
    assert.ok(mine.body.invoices.every(row => row.studentId === studentMed.id && row.events.length === 0));
    assert.equal((await request('/')).code, 403);
    currentId = foreign.id; assert.equal((await request('/my-invoices')).body.invoices.length, 0);
    const staff = await user(a.id, 'staff', 'staff'); currentId = staff.id;
    assert.equal((await request('/')).code, 403);
    await db.user.update({ where: { id: staff.id }, data: { permissions: ['finance.manage'] } });
    assert.equal((await request('/')).code, 200);
    await db.user.update({ where: { id: staff.id }, data: { permissions: [] } });
    assert.equal((await issue(studentMed.id, '2027-01', 3)).code, 403);
  } finally { await db.$disconnect(); }
});
